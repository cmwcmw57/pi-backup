import os
makefile_path = os.path.join(r"D:\STM32_Projects\rover_motor", "Makefile")
with open(makefile_path, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")

# Verify
with open(makefile_path, "r") as f:
    content = f.read()
tab_count = content.count("\t")
has_all = "all:" in content
print(f"Makefile written: {len(content)} bytes, {tab_count} tabs, all target: {has_all}")
